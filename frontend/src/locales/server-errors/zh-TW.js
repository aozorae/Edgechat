const dynamicErrorTranslations = [
  [/^可使用次数必须是 1 到 (\d+) 之间的整数$/, (match) => `可使用次數必須是 1 到 ${match[1]} 之間的整數`],
  [/^文件大小不能超过 ([\d.]+)MB$/, (match) => `文件大小不能超過 ${match[1]}MB`],
  [/^消息过大，最大 ([\d.]+)KB$/, (match) => `訊息過大，最大 ${match[1]}KB`],
  [/^Telegram API 请求失败：(\d+)$/, (match) => `Telegram API 請求失敗：${match[1]}`],
  [/^Telegram 文件下载失败：(\d+)$/, (match) => `Telegram 文件下載失敗：${match[1]}`],
  [/^演示接口未实现：(\w+) (.+)$/, (match) => `演示介面未實現：${match[1]} ${match[2]}`]
];

export function localizeServerError(message) {
  const fixed = fixedErrorTranslations.get(message);
  if (fixed) return fixed;
  for (const [pattern, translate] of dynamicErrorTranslations) {
    const match = message.match(pattern);
    if (match) return translate(match);
  }
  return message;
}
